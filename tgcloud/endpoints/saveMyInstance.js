import { db, EndpointError } from 'sdk';
import { eq, sql } from 'sdk/db';
import { telegramInstances } from '../schema.js';
import { validateInstanceInput } from '../lib/instance-input.js';

const requireTelegramUserId = (ctx) => {
  const userId = ctx?.initData?.user?.id;
  if (!Number.isSafeInteger(userId) || userId <= 0) {
    throw new EndpointError('Verified Telegram identity is required.', { code: 'UNAUTHORIZED' });
  }
  return userId;
};

export default async function (input, ctx) {
  const telegramUserId = requireTelegramUserId(ctx);
  const validation = validateInstanceInput(input);

  if (!validation.normalized) {
    // Expose only a stable field/category code. Never include candidate URLs,
    // query values, account IDs, relay public-key material, or input contents.
    throw new EndpointError(
      `Invalid OpenChamber instance metadata: ${validation.reason || 'invalid-payload'}.`,
      { code: 'INVALID_INSTANCE' },
    );
  }

  const normalized = validation.normalized;

  // The primary key guarantees one mapping per Telegram account. Keep the
  // instance ID generated by the first insert stable across devices and updates.
  await db.insert(telegramInstances).values({
    telegramUserId,
    instanceId: crypto.randomUUID(),
    serverId: normalized.serverId,
    label: normalized.label,
    candidates: normalized.candidates,
  }).onConflictDoUpdate({
    target: telegramInstances.telegramUserId,
    set: {
      serverId: normalized.serverId,
      label: normalized.label,
      candidates: normalized.candidates,
      updatedAt: sql`(unixepoch())`,
    },
  }).run();

  const saved = await db.select({ instanceId: telegramInstances.instanceId })
    .from(telegramInstances)
    .where(eq(telegramInstances.telegramUserId, telegramUserId))
    .get();

  if (!saved) {
    throw new EndpointError('The OpenChamber instance could not be saved.', { code: 'SAVE_FAILED' });
  }

  return { saved: true, instanceId: saved.instanceId };
}
